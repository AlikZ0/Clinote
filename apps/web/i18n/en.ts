/**
 * The shape of a catalogue: the same keys as English, with any string as a
 * value. Without the widening, `as const` would demand that a translation be
 * character-for-character the English text.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> }

export type Messages = Widen<typeof en>
